import sqlite3
import os

# Имя файла нашей базы данных
DB_NAME = "canteen.db"

# ШАГ 1: Если старый пустой файл базы данных существует, 
# мы его удаляем, чтобы структура со столбцами цен создалась правильно.
if os.path.exists(DB_NAME):
    try:
        os.remove(DB_NAME)
        print("Старый файл базы данных успешно удален для обновления структуры.")
    except Exception as e:
        print(f"Не удалось удалить старый файл базы (возможно, запущен сайт): {e}")

# Подключаемся к чистому файлу базы данных
conn = sqlite3.connect(DB_NAME)
cursor = conn.cursor()

# ШАГ 2: Создаем таблицу с тремя важными полями: название, количество и цена
cursor.execute("""
CREATE TABLE IF NOT EXISTS menu (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    quantity INTEGER DEFAULT 0,
    price INTEGER DEFAULT 0
)
""")

# ШАГ 3: Задаем стартовое школьное меню
# Формат данных: ("Название блюда", Количество порций на начало дня, Цена в рублях)
initial_dishes = [
    ("Борщ с капустой", 40, 45),
    ("Суп куриный с вермишелью", 35, 40),
    ("Котлета куриная с пюре", 50, 65),
    ("Макароны с сыром", 45, 35),
    ("Булочка с сахаром", 60, 20),
    ("Компот из сухофруктов", 80, 15),
    ("Чай с лимоном", 70, 12)
]

# ШАГ 4: Записываем наши продукты в базу данных
cursor.executemany(
    "INSERT INTO menu (name, quantity, price) VALUES (?, ?, ?)", 
    initial_dishes
)

# Сохраняем изменения в файле и закрываем соединение
conn.commit()
conn.close()

print("\n[УСПЕХ] База данных canteen.db полностью создана и заполнена!")
print("Список добавленных блюд, их количество и цены успешно сохранены.")
